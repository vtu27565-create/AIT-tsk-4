play_game()

# How Minimax works
# The algorithm considers **all possible future moves**:
# * **Computer (O)** tries to maximize the score.
# * **Human (X)** tries to minimize the score.
# * `+1` -> Computer wins
# * `-1` -> Human wins
# * `0` -> Draw
# The computer recursively explores possible moves until the game reaches a win, loss, or draw, then works backward to select the best move.
# Because Tic-Tac-Toe has only 9 squares, this basic Minimax implementation is fast enough to play perfectly.

